    '        ei_list[k] = ei_list[k] + offset',
    '        offset += n',
    '    with torch.cuda.stream(transfer_stream):',
    '        batched = {',
    '            "x": torch.cat(x_list, dim=0).to(device, non_blocking=True),',
    '            "edge_index": torch.cat(ei_list, dim=1).to(device, non_blocking=True),',
