    '',
    'def collate_fast(indices):',
    '    x_list = [g_x[i] for i in indices]',
    '    ei_list = [g_ei[i] for i in indices]',
    '    batch_list = []',
    '    offset = 0',
    '    for k, x in enumerate(x_list):',
    '        n = x.size(0)',
